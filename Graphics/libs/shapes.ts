// Cara amarilla con dientes de conejo
function nerdFace(radius: number) : twgl.Arrays {
    const sides = 36;
    const positionData: number[] = [];
    const colorData: number[] = [];
    const indexData: number[] = [];

    // Cabeza: centro (0) + borde (1 a sides)
    positionData.push(0, 0);
    colorData.push(0.9, 0.8, 0, 1);
    for (let s = 0; s < sides; s++) {
        const angle = 2 * Math.PI * s / sides;
        positionData.push(radius * Math.cos(angle), radius * Math.sin(angle));
        colorData.push(0.9, 0.8, 0, 1);
        // Centro, vértice actual, siguiente
        indexData.push(0, s + 1, (s + 1) % sides + 1);
    }

    // Dientes
    const t = sides + 1;    // primer vértice de los dientes
    positionData.push(...[
        -0.11, -0.25,   -0.01, -0.25,   -0.01, -0.40,   -0.11, -0.40,   // izquierdo
         0.01, -0.25,    0.11, -0.25,    0.11, -0.40,    0.01, -0.40,   // derecho
    ].map(e => radius * e));
    colorData.push(...new Array(8).fill([1, 1, 1, 1]).flat());
    indexData.push(t, t + 1, t + 2,       t, t + 2, t + 3,
                   t + 4, t + 5, t + 6,   t + 4, t + 6, t + 7);

    return {
        a_position: { numComponents: 2, data: positionData },
        a_color:    { numComponents: 4, data: colorData },
        indices:    { numComponents: 3, data: indexData },
    };
}

